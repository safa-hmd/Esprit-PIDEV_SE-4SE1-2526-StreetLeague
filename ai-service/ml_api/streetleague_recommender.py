def predict_for_user(user_id, top_k=4, exclude_ids=None):
    """Simulation de l'appel .predict() côté API"""
    if user_id not in pivot_train.index:
        return {"user_id": user_id, "recommendations": prod_ids[:top_k], "note": "Cold Start (fallback popularité)"}

    u_idx = list(pivot_train.index).index(user_id)
    user_vec = X_train[u_idx].reshape(1, -1)
    _, sim_idxs = model.kneighbors(user_vec, n_neighbors=top_k+1)

    neighbor_data = X_train[sim_idxs[0][1:]]
    scores = np.sum(neighbor_data, axis=0)

    bought = np.where(user_vec.flatten() > 0)[0]
    scores[bought] = -np.inf
    if exclude_ids:
        for pid in exclude_ids:
            if pid in prod_ids:
                scores[list(prod_ids).index(pid)] = -np.inf

    top_idxs = np.argsort(scores)[::-1][:top_k]
    recs = [prod_ids[i] for i in top_idxs]
    return {"user_id": user_id, "recommendations": recs}

test_uid = np.random.choice(user_ids)
result = predict_for_user(test_uid, top_k=4)
